import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { pinSkills, SkillStore } from '../src/skills.js';
import { Workspace } from '../src/workspace.js';

test('owner-published Skill versions reopen and export their original native package', async t => {
  const temp = await mkdtemp(join(tmpdir(), 'kada-skill-authoring-'));
  t.after(() => rm(temp, { recursive: true, force: true, maxRetries: 5 }));
  const workspace = await Workspace.open(join(temp, 'project'));
  const data = join(temp, 'host');
  const source = join(workspace.root, 'draft');
  await mkdir(join(source, 'references', 'empty'), { recursive: true });
  await writeFile(join(source, 'references', 'notes.txt'), '\ufeffOriginal UTF-8 bytes.\n');
  const body = (value: string) => `---\nname: sample-report\ndescription: Verify a synthetic project report.\n---\n\n${value}\n`;
  await writeFile(join(source, 'SKILL.md'), body('First instructions.'));
  let store = await SkillStore.open(data);
  const first = await store.importVersion(workspace, 'draft');
  const original = await pinSkills(workspace, join(temp, 'run-1'), store, [{ name: first.name, version: first.version }]);
  assert.equal(await readFile(original.pins[0]!.filePath, 'utf8'), body('First instructions.'));
  await writeFile(join(source, 'SKILL.md'), body('Updated instructions.'));
  await assert.rejects(store.importVersion(workspace, 'draft'), /current version/i);
  const second = await store.importVersion(workspace, 'draft', first.version);
  assert.notEqual(second.version, first.version);
  store = await SkillStore.open(data);
  const current = (await store.catalog(workspace)).find(item => item.name === first.name);
  assert.equal(current?.currentVersion, second.version);
  assert.deepEqual(current?.versions, [first.version, second.version]);
  const portable = await store.exportVersion(workspace, first, 'reviewed-skill');
  assert.equal(await readFile(join(portable.path, 'SKILL.md'), 'utf8'), body('First instructions.'));
  assert.equal(await readFile(join(portable.path, 'references', 'notes.txt'), 'utf8'), '\ufeffOriginal UTF-8 bytes.\n');
  assert.deepEqual(await readdir(join(portable.path, 'references', 'empty')), []);
  assert.deepEqual(await store.exportVersion(workspace, first, 'reviewed-skill'), portable);
  assert.deepEqual(await store.importVersion(workspace, 'reviewed-skill'), first);
  assert.equal((await store.catalog(workspace)).find(item => item.name === first.name)?.currentVersion, second.version);
  await assert.rejects(store.exportVersion(workspace, second, 'reviewed-skill'), /destination/i);
  assert.equal(await readFile(original.pins[0]!.filePath, 'utf8'), body('First instructions.'));
});
